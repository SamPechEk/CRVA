function model(
  id: string,
  name: string,
  presentation: string,
  n: number,
  energy: string,
  mix: string,
  recipe: Record<string, string>,
  ref = false,
): CandleModel {
  return {
    id,
    code: id,
    name,
    presentation,
    batchConfig: {
      candlesPerBatch: n,
      meltPourMinutesBatch: "6",
      unmoldPackMinutesBatch: "10",
      curingHoursPassive: "24",
      energyKwhBatch: energy,
    },
    recipeItems: Object.entries({
      ...recipe,
      "IND-01": "0",
      "IND-02": "0",
    }).map(([materialId, quantityPerCandle]) => ({
      modelId: id,
      materialId,
      quantityPerCandle,
    })),
    salesMixPct: mix,
    imageUrl: null,
    imagePublicId: null,
    isReferenceTemplate: ref,
    isActive: true,
  };
}
